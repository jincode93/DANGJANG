def poly(points):
    return "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in points) + "z"


def gear():
    pts = []
    for i in range(8):
        t = i * 45
        for a, r in ((-21, 6.4), (-11, 8.6), (11, 8.6), (21, 6.4)):
            pts.append((12 + r * math.cos(math.radians(t + a)), 12 + r * math.sin(math.radians(t + a))))
    return poly(pts)


def badge():
    pts = []
    for i in range(24):
        r = 8.8 if i % 2 == 0 else 7.4
        a = math.radians(i * 15 - 90)
        pts.append((12 + r * math.cos(a), 12 + r * math.sin(a)))
    return poly(pts)


